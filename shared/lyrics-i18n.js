/** Looks up `key` in `lang`, falling back to English, and fills {placeholders}. */
export function lyT(lang, key, vars) {
  const text = (STRINGS[lang] ?? STRINGS.en)[key] ?? STRINGS.en[key] ?? key;
  return Object.entries(vars ?? {}).reduce((out, [name, value]) => out.replaceAll(`{${name}}`, String(value)), text);
}
